# --- Фрагмент А ---
# Причина: значения "2" и "3" записаны в кавычках — это строки (str), поэтому + их склеивает, а не складывает.
first = "2"
second = "3"

print(f"Тип до преобразования: {type(first)}, {type(second)}")

# Преобразуем строки в целые числа
first = int(first)
second = int(second)

print(f"Тип после преобразования: {type(first)}, {type(second)}")
print(f"Фрагмент А (Сумма): {first + second}\n")


# --- Фрагмент Б ---
# Причина: функция input() всегда возвращает строку (str), а сложить строку и число (age + 1) в Python нельзя.
age = input("Возраст: ")

print(f"Тип до преобразования: {type(age)}")

# Преобразуем введенную строку в число
age = int(age)

print(f"Тип после преобразования: {type(age)}")
print(f"Фрагмент Б (Возраст через год): {age + 1}\n")


# --- Фрагмент В ---
# Причина: из-за приоритета операций сначала выполняется деление (third / 3), а потом сложение. Нужно использовать скобки.
first = 4
second = 7
third = 10

average = (first + second + third) / 3
print(f"Фрагмент В (Среднее значение): {average}")