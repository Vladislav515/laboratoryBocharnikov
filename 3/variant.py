n = int(input("Введите целое число от 0 до 100: "))

# Сначала проверяем выход за допустимый диапазон [0; 100]
if n < 0 or n > 100:
    print("Ошибка диапазона")

# Вариант 1: Заряд аккумулятора (0-19: Низкий, 20-79: Средний, 80-100: Высокий)
elif 0 <= n <= 19:
    print("Низкий")
elif 20 <= n <= 79:
    print("Средний")
else:  # n от 80 до 100
    print("Высокий")